def parse_level(s):
    rows = [r for r in s.strip().split('\n') if r.strip()]
    lvl = [[0] * WW for _ in range(WH)]
    leg = {'.': 0, 'G': 1, 'B': 2, 'Q': 3, 'P': 4, 'p': 5, 'T': 6, 't': 7,
           'U': 8, 'D': 9, 'S': 10, 'K': 11, 'F': 12, 'C': 13, 'M': 14, 'O': 15}
    for y, row in enumerate(rows[-WH:]):
        for x, ch in enumerate(row[:WW]):
            if ch.upper() in leg:
                lvl[WH - 1 - y][x] = leg[ch.upper()]
            if ch == 'g':
                lvl[WH - 1 - y][x] = 1
            if ch == 'D':
                lvl[WH - 1 - y][x] = 9
    return lvl
